"""Build the demo tables from the recorded transcripts, so the write-ups show every turn as run.

Reads ``results/demo/fix17cs37_82.json`` (6.37) and ``results/demo/base_r175.json`` (base, run at
the same commit), plus ``v5_82.json`` and ``fix15_82.json`` for the two questions 6.37 answers
wrong (R-175). Writes ``docs/demo.md``. The grades are the expected answers below, fixed as the
facts are written in ``demo/chat.txt``; nothing is graded by matching words.

Usage:
    python scripts/make_demo_table.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEMO = REPO_ROOT / "results" / "demo"
OUT = REPO_ROOT / "docs" / "demo.md"

# Turn number (1-based) -> the fact as demo/chat.txt states it.
QUESTIONS = {
    10: "Thursdays (turn 1)",
    11: "Halifax (turn 5)",
    12: "never told",
    14: "the leak under the kitchen sink (turn 3)",
}
# (turn, model) -> grade, read by hand from the replies against QUESTIONS.
GRADES = {
    (10, "6.37"): "right",
    (10, "base"): "wrong: says it has no access",
    (11, "6.37"): "right",
    (11, "base"): "wrong: says it has no access",
    (12, "6.37"): "wrong: gives the Tobias fact",
    (12, "base"): "right",
    (14, "6.37"): "wrong: gives the pottery fact",
    (14, "base"): "close guess: says a leaky faucet, with turn 3 out of view and no search",
    (12, "v5"): "right: declines",
    (14, "v5"): "wrong: declines",
    (12, "fix 15"): "right: declines",
    (14, "fix 15"): "wrong: declines",
}


def turns(name: str) -> list[dict]:
    return json.loads((DEMO / f"{name}.json").read_text(encoding="utf-8"))["turns"]


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip()


def searched(turn: dict) -> str:
    return "; ".join(f"`{q}`" for q in turn["queries"]) or "none"


def main() -> None:
    tuned, base = turns("fix17cs37_82"), turns("base_r175")
    old = {"v5": turns("v5_82"), "fix 15": turns("fix15_82")}
    plain = [n for n in range(1, len(tuned) + 1) if n not in QUESTIONS]
    lines = [
        "# The scripted demo, every turn",
        "",
        "Generated by `scripts/make_demo_table.py` from `results/demo/` (R-175). Greedy decoding,",
        "the last three exchanges in view, the search tool over older messages.",
        "",
        f"Plain chat lines searched: 6.37 {sum(bool(tuned[n - 1]['queries']) for n in plain)} of "
        f"{len(plain)}, base {sum(bool(base[n - 1]['queries']) for n in plain)} of {len(plain)}.",
        "",
        "| Turn | Message | 6.37 search | 6.37 reply | Base search | Base reply |",
        "|---|---|---|---|---|---|",
    ]
    for n, (t, b) in enumerate(zip(tuned, base, strict=True), 1):
        lines.append(
            f"| {n} | {cell(t['message'])} | {searched(t)} | {cell(t['reply'])} | {searched(b)} "
            f"| {cell(b['reply'])} |"
        )
    lines += [
        "",
        "## The four questions",
        "",
        "| Turn | Expected | 6.37 | Base |",
        "|---|---|---|---|",
    ]
    for n, fact in QUESTIONS.items():
        lines.append(f"| {n} | {fact} | {GRADES[(n, '6.37')]} | {GRADES[(n, 'base')]} |")
    lines += [
        "",
        "## Earlier adapters on the two questions 6.37 gets wrong",
        "",
        "| Turn | Adapter | Search | Reply | Grade |",
        "|---|---|---|---|---|",
    ]
    for n in (12, 14):
        for name, run in old.items():
            t = run[n - 1]
            lines.append(
                f"| {n} | {name} | {searched(t)} | {cell(t['reply'])} | {GRADES[(n, name)]} |"
            )
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
